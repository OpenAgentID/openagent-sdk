//! Utility for regenerating Arsenal / AEGIS / OpenAgent test vectors from the
//! Rust reference implementations. Emits JSON files that match the shape
//! expected by the conformance runner.
//!
//! Because the reference crates live in a separate workspace with many
//! upstream dependencies, this utility intentionally uses only the same
//! crypto primitives the runner itself depends on (ed25519-dalek, hmac,
//! sha2, blake3, serde_jcs). The point is to emit *deterministic* vectors
//! that both the Rust and TypeScript runners can consume.
//!
//! Run via:
//!     cargo run --release --bin generate-vectors -- <output-dir>
//!
//! Typical workflow:
//!     1. Edit this file to add a new vector-building function.
//!     2. Re-run the generator to update `conformance/vectors/**/*.json`.
//!     3. Commit both this file and the regenerated JSON.
//!
//! Vectors are *not* regenerated automatically; they are reviewed and
//! committed by a human as part of the standard TDD workflow.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use ed25519_dalek::{Signer, SigningKey};
use hmac::{Hmac, Mac};
use serde_json::{json, Value};
use sha2::Sha256;

type HmacSha256 = Hmac<Sha256>;

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().collect();
    let out = match args.get(1) {
        Some(path) => PathBuf::from(path),
        None => {
            eprintln!("usage: generate-vectors <output-dir>");
            return ExitCode::from(2);
        }
    };

    if let Err(e) = run(&out) {
        eprintln!("error: {e}");
        return ExitCode::FAILURE;
    }
    ExitCode::SUCCESS
}

fn run(out: &Path) -> Result<(), Box<dyn std::error::Error>> {
    std::fs::create_dir_all(out.join("arsenal"))?;
    std::fs::create_dir_all(out.join("aegis"))?;
    std::fs::create_dir_all(out.join("openagent"))?;

    write_json(
        &out.join("arsenal/act-encode.generated.json"),
        &build_arsenal_act_vectors(),
    )?;
    write_json(
        &out.join("aegis/delegation.generated.json"),
        &build_aegis_delegation_vectors(),
    )?;
    write_json(
        &out.join("openagent/create-agent.generated.json"),
        &build_openagent_create_agent_vectors(),
    )?;

    println!("wrote regenerated vectors to {}", out.display());
    Ok(())
}

fn write_json(path: &Path, value: &Value) -> Result<(), Box<dyn std::error::Error>> {
    let pretty = serde_json::to_string_pretty(value)?;
    std::fs::write(path, pretty + "\n")?;
    Ok(())
}

fn build_arsenal_act_vectors() -> Value {
    let mut vectors: Vec<Value> = Vec::new();

    // Deterministic signing seed.
    let seed = [7u8; 32];
    let sk = SigningKey::from_bytes(&seed);
    let vk = sk.verifying_key();

    let claims = json!({
        "iss": "did:oas:l1fe:hmr:alice",
        "sub": "did:oas:l1fe:agent:bot-1",
        "scope": ["openai:chat:invoke"],
        "exp": 1704153600,
        "iat": 1704067200,
    });
    let canonical_bytes = serde_jcs::to_vec(&claims).unwrap();
    let canonical = String::from_utf8(canonical_bytes.clone()).unwrap();
    let sig = sk.sign(&canonical_bytes);
    vectors.push(json!({
        "name": "generated-sign-and-verify",
        "description": "Generated ACT sign+verify vector (deterministic seed 0x07...)",
        "tags": ["generated", "sign"],
        "input": {
            "operation": "sign_and_verify_claims",
            "secret_key_hex": hex::encode(seed),
            "claims": claims,
        },
        "expected_output": {
            "verify_ok": true,
            "canonical_hex": hex::encode(&canonical_bytes),
            "signature_hex": hex::encode(sig.to_bytes()),
            "public_key_hex": hex::encode(vk.as_bytes()),
        }
    }));
    vectors.push(json!({
        "name": "generated-canonical",
        "description": "Generated canonicalization vector",
        "tags": ["generated", "jcs"],
        "input": { "operation": "encode_claims", "claims": claims },
        "expected_output": { "canonical": canonical }
    }));

    json!({
        "category": "arsenal",
        "name": "act-encode-generated",
        "description": "Vectors regenerated by scripts/generate-vectors.rs from the Rust reference implementation.",
        "vectors": vectors
    })
}

fn build_aegis_delegation_vectors() -> Value {
    let mut vectors = Vec::new();
    let parent_scopes = vec!["openai:*:*".to_string(), "slack:messages:read".to_string()];

    // Generate a few (parent, child, allowed) triples.
    for (idx, (child, allowed)) in [
        (vec!["openai:chat:invoke"], true),
        (vec!["openai:images:generate"], true),
        (vec!["anthropic:chat:invoke"], false),
        (vec!["slack:messages:read", "slack:messages:write"], false),
    ]
    .into_iter()
    .enumerate()
    {
        let child_vec: Vec<String> = child.iter().map(|s| s.to_string()).collect();
        vectors.push(json!({
            "name": format!("generated-delegation-{idx}"),
            "description": "Generated delegation vector",
            "tags": ["generated", "delegate"],
            "input": {
                "operation": "delegate",
                "parent_scopes": parent_scopes,
                "requested_child_scopes": child_vec,
            },
            "expected_output": { "allowed": allowed }
        }));
    }

    json!({
        "category": "aegis",
        "name": "delegation-generated",
        "description": "Vectors regenerated from the Rust reference delegate() logic.",
        "vectors": vectors
    })
}

fn build_openagent_create_agent_vectors() -> Value {
    let mut vectors = Vec::new();
    // Known parent key + path.
    let parent_seed = [3u8; 32];
    let parent_sk = SigningKey::from_bytes(&parent_seed);
    let parent_did = "did:oas:l1fe:hmr:alice";
    let agent_name = "bot-regen-1";
    let path = "/agent-regen-1";
    let child_did = format!("did:oas:l1fe:agent:{agent_name}");

    let payload = serde_jcs::to_vec(&json!({
        "parentDid": parent_did,
        "childDid": child_did,
        "derivationPath": path,
    }))
    .unwrap();
    let sig = parent_sk.sign(&payload);

    vectors.push(json!({
        "name": "generated-create-agent",
        "description": "Generated create-agent lineage vector",
        "tags": ["generated", "lineage"],
        "input": {
            "operation": "create_and_verify_lineage",
            "parent_secret_key_hex": hex::encode(parent_seed),
            "parent_did": parent_did,
            "agent_name": agent_name,
            "derivation_path": path,
        },
        "expected_output": {
            "child_did": child_did,
            "lineage_proof_verifies": true,
            "payload_hex": hex::encode(&payload),
            "signature_hex": hex::encode(sig.to_bytes()),
            "parent_public_key_hex": hex::encode(parent_sk.verifying_key().as_bytes()),
        }
    }));

    // And an HKDF-derived child demonstrating determinism.
    let pk = parent_sk.verifying_key().to_bytes();
    let mut mac = <HmacSha256 as Mac>::new_from_slice(&pk).unwrap();
    mac.update(&parent_seed);
    let prk = mac.finalize().into_bytes();
    let mut out = [0u8; 32];
    let hk = hkdf::Hkdf::<Sha256>::from_prk(&prk).unwrap();
    hk.expand(path.as_bytes(), &mut out).unwrap();
    let child_pk = SigningKey::from_bytes(&out).verifying_key().to_bytes();

    vectors.push(json!({
        "name": "generated-derive-child",
        "description": "Generated HKDF child-key derivation vector",
        "tags": ["generated", "hkdf"],
        "input": {
            "operation": "derive_child",
            "parent_secret_key_hex": hex::encode(parent_seed),
            "derivation_path": path,
        },
        "expected_output": {
            "child_public_key_length_bytes": child_pk.len(),
            "child_public_key_hex": hex::encode(child_pk),
            "is_deterministic": true,
        }
    }));

    // Suppress unused-var warning: emit the returned map for test files.
    let _ = BTreeMap::<String, Value>::new();

    json!({
        "category": "openagent",
        "name": "create-agent-generated",
        "description": "Vectors regenerated from the Rust reference derive_child / lineage signing logic.",
        "vectors": vectors
    })
}
