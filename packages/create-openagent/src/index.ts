import { resolve } from 'node:path';
import { existsSync, realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import metadata from '../package.json';
import { parseArguments, collectOptions } from './prompts.js';
import { scaffold } from './scaffold.js';

export { parseArguments, validateProjectName, collectOptions } from './prompts.js';
export { scaffold } from './scaffold.js';
export { generateStarterTemplate } from './templates/starter.js';

const help = `create-openagent — local, open agent identity starter\n\nUsage: create-openagent <project-name> [--yes] [--template starter]\n\n  --yes, -y         Create without prompts (requires a name)\n  --template starter  The runnable Node 20.19+ starter (default)\n  --help, -h        Show help\n  --version, -v     Show version\n\nNo account or hosted identity service is required.\nHistorical templates, adapters, bridges and deployment flags need migration\nand are not generated by this release.\n`;

export async function runCli(args: readonly string[] = process.argv.slice(2)): Promise<number> {
  try {
    const input = parseArguments(args);
    if (input.kind !== 'create') {
      process.stdout.write(input.kind === 'help' ? help : metadata.version + '\n'); return 0;
    }
    const options = await collectOptions(input);
    await scaffold(options);
    process.stdout.write('Created ' + options.projectName + '/\n\n  cd ' + options.projectName + '\n  npm install\n  npm run dev\n\nThen, in another terminal: npm run agent -- "Hello from my agent"\n');
    return 0;
  } catch (error) {
    process.stderr.write('create-openagent: ' + (error instanceof Error ? error.message : 'Failed to create project.') + '\n');
    return 1;
  }
}

if (process.argv[1] && existsSync(process.argv[1]) && realpathSync(resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  process.exitCode = await runCli();
}
