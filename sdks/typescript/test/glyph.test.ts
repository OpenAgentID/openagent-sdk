import { describe, expect, it } from 'vitest';
import { agentAvatar, glyphCodeword, glyphEndpoint, oasGlyph, parseAvatarOverride } from '../src/glyph.js';
import { didSchema, resolveConfig } from '../src/config.js';
import { parseIdentityDocument } from '../src/identity.js';
import { readFileSync } from 'node:fs';
import { getCharacterExpressions, getCharacterSkins, renderCharacterSvg } from '../src/characters.js';

interface ReferenceColor { hex: string; rgba: number[] }
interface ReferenceVector {
  did: string;
  codeword: { hex: string };
  palette: { background: ReferenceColor; finder_dark: ReferenceColor; finder_light: ReferenceColor; kind_accent: ReferenceColor; data_colors: ReferenceColor[] };
  grid: { cells: { type: string; value: number; shape: string; hue_shift: number }[] };
}
// Generated by the unmodified upstream Rust modules on Depot, not this SDK.
const reference = JSON.parse(readFileSync(new URL('../../../conformance/fixtures/glyph/avatar-v1.json', import.meta.url), 'utf8')) as { vectors: ReferenceVector[] };

// Existing upstream public conformance DID, never a private key or live user.
const did = 'did:oas:openagent:agent:z6MkhaXgBZDvotDkL5257faiztiGiC2QtKLGpbnnEGta2doK';
describe('OAS Glyph avatars', () => {
  it.each(reference.vectors)('matches independent Rust payload, palette and grid for $did', (vector) => {
    expect(Buffer.from(glyphCodeword(vector.did)).toString('hex')).toBe(vector.codeword.hex);
    const shapes = [...oasGlyph(vector.did).matchAll(/<(rect|circle|polygon)\b[^>]*>/g)].map(match => ({ tag: match[1], markup: match[0] }));
    const fill = (index: number): string | undefined => /fill="([^"]+)"/.exec(shapes[index]!.markup)?.[1];
    expect(fill(0)).toBe(vector.palette.background.hex);
    let index = 1;
    for (const cell of vector.grid.cells) {
      if (cell.type === 'alignment') {
        expect(fill(index++)).toBe(vector.palette.finder_light.hex);
        expect(fill(index++)).toBe(vector.palette.finder_dark.hex);
        continue;
      }
      let expected: string;
      if (cell.type === 'data') {
        expected = vector.palette.data_colors[cell.hue_shift]!.hex;
        expect(shapes[index]!.tag).toBe(({ Square: 'rect', Circle: 'circle', Diamond: 'polygon', Triangle: 'polygon' })[cell.shape as 'Square' | 'Circle' | 'Diamond' | 'Triangle']);
      } else if (cell.type === 'finder') {
        expected = (cell.value > 32 ? vector.palette.finder_dark : vector.palette.finder_light).hex;
      } else if (cell.type === 'kind') {
        const rgba = vector.palette.background.rgba.map((value, channel) => Math.floor(value + (vector.palette.kind_accent.rgba[channel]! - value) * cell.value / 63));
        expected = '#' + rgba.slice(0, 3).map(value => value.toString(16).padStart(2, '0')).join('');
      } else expected = vector.palette.background.hex;
      expect(fill(index++)).toBe(expected);
    }
    expect(index).toBe(shapes.length);
  });
  it('is deterministic, has all grid regions, and changes with the identity', () => {
    const svg = oasGlyph(did);
    expect(oasGlyph(did)).toBe(svg);
    expect(svg).toContain('viewBox="0 0 512 512"');
    expect(svg).toContain('<circle');
    expect(svg).toContain('<polygon');
    expect(oasGlyph(did.replace(':agent:', ':tool:'))).not.toBe(svg);
    expect(glyphCodeword(did)[0]).toBe(0x13);
    expect(glyphCodeword(did).length).toBeLessThanOrEqual(72);
  });
  it('keeps legacy identity readable and preserves its distinct avatar', () => {
    const legacy = did.replace('did:oas:openagent:', 'did:l1fe:');
    expect(didSchema.parse(legacy)).toBe(legacy);
    expect(oasGlyph(legacy)).not.toBe(oasGlyph(did));
    expect(resolveConfig({}).namespace).toBe('openagent');
    const named = 'did:l1fe:agent:agent-1';
    expect(glyphCodeword(named)[0]).toBe(0x23);
    expect(oasGlyph(named)).toContain('<svg');
    expect(oasGlyph(named)).not.toBe(oasGlyph('did:l1fe:agent:agent-2'));
  });
  it('uses a changeable HTTPS override and clearing it restores the default Autos skin', () => {
    const override = 'https://images.example.org/agent.png';
    expect(agentAvatar(did, { avatarOverride: override })).toBe(override);
    expect(agentAvatar(did, { avatarOverride: null })).toMatch(/^data:image\/svg\+xml/);
    expect(decodeURIComponent(agentAvatar(did).split(',')[1]!)).toBe(renderCharacterSvg(did));
    const document = { did, parent: did.replace(':agent:', ':hmr:'), publicKeyMultibase: did.split(':').at(-1), kind: 'agent', scopes: [], createdAt: '2026-10-11T00:00:00Z', avatarOverride: override };
    expect(parseIdentityDocument(document).avatarOverride).toBe(override);
    for (const bad of ['javascript:alert(1)', 'data:image/svg+xml,<svg/>', 'http://images.example.org/a', 'https://user:secret@example.org/a']) {
      expect(() => parseAvatarOverride(bad)).toThrow();
      expect(() => parseIdentityDocument({ ...document, avatarOverride: bad })).toThrow();
    }
  });
  it('keeps profile skin and preferred expression independent, with runtime eye state', () => {
    const profile = { avatarSkin: { skin: 'spacex' as const, shape: 'cloud' as const }, avatarExpression: 'curious' as const };
    const decode = (url: string): string => decodeURIComponent(url.split(',')[1]!);
    expect(decode(agentAvatar(did, profile, { animated: false }))).toBe(renderCharacterSvg(did, {
      skin: 'spacex', shape: 'cloud', expression: 'curious', animated: false,
    }));
    expect(decode(agentAvatar(did, profile, { expression: 'happy', animated: false, state: { blink: 0.5 } })))
      .toBe(renderCharacterSvg(did, { skin: 'spacex', shape: 'cloud', expression: 'happy', animated: false, state: { blink: 0.5 } }));
    expect(decode(agentAvatar(did, { avatarSkin: null }))).toBe(oasGlyph(did));
    const human = did.replace(':agent:', ':hmr:');
    expect(decode(agentAvatar(human))).toBe(oasGlyph(human));
    const document = { did, parent: human, publicKeyMultibase: did.split(':').at(-1), kind: 'agent', scopes: [], createdAt: '2026-10-11T00:00:00Z' };
    for (const avatarExpression of getCharacterExpressions()) {
      expect(parseIdentityDocument({ ...document, ...profile, avatarExpression }).avatarExpression).toBe(avatarExpression);
    }
    expect(parseIdentityDocument({ ...document, ...profile }).avatarSkin).toEqual(profile.avatarSkin);
    expect(parseIdentityDocument({ ...document, avatarSkin: null }).avatarSkin).toBeNull();
    for (const avatarSkin of [{ skin: 'unknown' }, { skin: 'spacex', shape: 'slender' }, { skin: 'autos', shape: 'circle' }, { skin: 'autos', expression: 'happy' }, { skin: 'autos', skinVersion: 2 }, { skin: 'autos', eyeStyle: 'other' }, { shape: 'standard' }]) {
      expect(() => parseIdentityDocument({ ...document, avatarSkin })).toThrow();
      expect(() => agentAvatar(did, { avatarSkin: avatarSkin as never })).toThrow();
    }
    expect(() => parseIdentityDocument({ ...document, avatarExpression: 'unknown' })).toThrow();
    expect(() => agentAvatar(did, { avatarSkin: { skin: 'autos', size: 64 } as never })).toThrow();
    expect(() => agentAvatar(did, profile, { expression: null as never })).toThrow();
  });
  it('passes avatar/full framing through the profile wrapper for every family and kind', () => {
    const decode = (url: string): string => decodeURIComponent(url.split(',')[1]!);
    let kinds = 0;
    for (const skin of getCharacterSkins()) for (const shape of skin.shapes) {
      const profile = { avatarSkin: { skin: skin.id, shape }, avatarExpression: 'thoughtful' as const };
      const cropped = decode(agentAvatar(did, profile, { animated: false, size: 32 }));
      expect(cropped).toBe(renderCharacterSvg(did, { skin: skin.id, shape, expression: 'thoughtful', size: 32, animated: false }));
      expect(cropped).toContain('data-character-view="avatar"');
      const full = decode(agentAvatar(did, profile, { view: 'full', expression: 'concerned', animated: false, size: 128,
        state: { blink: 0.5, gaze: { x: 1, y: -1 } } }));
      expect(full).toBe(renderCharacterSvg(did, { skin: skin.id, shape, view: 'full', expression: 'concerned', size: 128,
        animated: false, state: { blink: 0.5, gaze: { x: 1, y: -1 } } }));
      // A One is the whole head in both views; the other families widen to the full character.
      expect(full).toContain(skin.id === 'one' ? 'viewBox="-100 -100 200 200"' : 'viewBox="0 0 512 512"');
      expect(full).toContain('data-character-view="full"');
      kinds++;
    }
    expect(kinds).toBe(75);
    // Explicit Glyph and human profiles retain the original Glyph framing/bytes.
    for (const view of ['avatar', 'full'] as const) {
      expect(decode(agentAvatar(did, { avatarSkin: null }, { view }))).toBe(oasGlyph(did));
      const human = did.replace(':agent:', ':hmr:');
      expect(decode(agentAvatar(human, {}, { view }))).toBe(oasGlyph(human));
    }
  });
  it('rejects invalid view and cross-family profile selectors before rendering a character', () => {
    for (const view of [null, 'portrait', 'full\n', 1, true, {}]) {
      expect(() => agentAvatar(did, {}, { view: view as never })).toThrow();
    }
    for (const avatarSkin of [
      { skin: 'fold', shape: 'bud' }, { skin: 'purl', shape: 'teapot' },
      { skin: 'halloween', shape: 'turkey' }, { skin: 'thanksgiving', shape: 'ornament' },
      { skin: 'christmas', shape: 'ghost' },
    ]) expect(() => agentAvatar(did, { avatarSkin: avatarSkin as never })).toThrow();
  });
  it('rejects markup, malformed identifiers, excessive payloads and invalid sizes', () => {
    for (const bad of ['<script/>', did + '"/>', did.replace('z6Mkha', 'z0OIl'), did.replace(/z[^:]+$/, 'z' + 'A'.repeat(80))]) {
      expect(() => oasGlyph(bad)).toThrow();
    }
    for (const size of [0, 31, 2049, 256.5, NaN, Infinity]) expect(() => oasGlyph(did, { size })).toThrow();
  });
  it('serves safe SVG with immutable caching and no external image fetch', async () => {
    const url = 'https://identity.example.org/v1/glyph/svg/' + encodeURIComponent(did);
    const response = glyphEndpoint(new Request(url));
    expect(response.status).toBe(200);
    expect(response.headers.get('content-type')).toContain('image/svg+xml');
    expect(response.headers.get('x-content-type-options')).toBe('nosniff');
    expect(response.headers.get('content-security-policy')).toContain("default-src 'none'");
    expect(await response.text()).toBe(oasGlyph(did));
    expect(glyphEndpoint(new Request(url, { headers: { 'if-none-match': response.headers.get('etag')! } })).status).toBe(304);
    expect(await glyphEndpoint(new Request(url, { method: 'HEAD' })).text()).toBe('');
    expect(glyphEndpoint(new Request(url, { method: 'POST' })).status).toBe(405);
    expect(glyphEndpoint(new Request(url + '?size=NaN')).status).toBe(400);
    expect(glyphEndpoint(new Request(url + '?background=x')).status).toBe(400);
  });
});
